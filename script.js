// Dynamic background color change based on section
const sections = document.querySelectorAll('section');
const body = document.body;

const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const sectionId = entry.target.id;
            
            // Remove all section classes
            body.classList.remove('hero-active', 'about-active', 'interests-active', 'projects-active', 'contact-active');
            
            // Add current section class
            if (sectionId) {
                body.classList.add(`${sectionId}-active`);
            }
        }
    });
}, {
    threshold: 0.5
});

sections.forEach(section => {
    sectionObserver.observe(section);
});

// Add loading animation
window.addEventListener('load', () => {
    document.body.classList.add('loaded');
});

// Smooth reveal animation for stats
const statsObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const statNumber = entry.target.querySelector('.stat-number');
            const finalNumber = parseInt(statNumber.textContent);
            let currentNumber = 0;
            
            const increment = finalNumber / 50;
            const timer = setInterval(() => {
                currentNumber += increment;
                if (currentNumber >= finalNumber) {
                    currentNumber = finalNumber;
                    clearInterval(timer);
                }
                statNumber.textContent = Math.floor(currentNumber) + (finalNumber > 10 ? '+' : '');
            }, 30);
        }
    });
}, { threshold: 0.5 });

document.querySelectorAll('.stat-item').forEach(stat => {
    statsObserver.observe(stat);
});